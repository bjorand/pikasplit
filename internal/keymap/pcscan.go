package keymap

// FromPCScancode converts a PC scancode (set 1, as reported by Windows in
// WM_KEYDOWN lParam or KBDLLHOOKSTRUCT) to a USB HID usage ID. extended is
// the E0 prefix flag. It returns ok=false for unknown keys.
//
// Pause and NumLock share scancode 0x45 and are reported inconsistently by
// Windows; callers should disambiguate them by virtual key (VK_PAUSE,
// VK_NUMLOCK) and use HIDPause / HIDNumLock directly.
func FromPCScancode(scan uint16, extended bool) (hid uint16, ok bool) {
	if scan > 0x7F {
		return 0, false
	}
	var v uint8
	if extended {
		v = pcExtended[scan]
	} else {
		v = pcBase[scan]
	}
	return uint16(v), v != 0
}

// HID usages Windows callers need to reference directly.
const (
	HIDPause   = 0x48
	HIDNumLock = 0x53
)

var pcBase = [0x80]uint8{
	0x01: 0x29,                                                 // Escape
	0x02: 0x1E, 0x03: 0x1F, 0x04: 0x20, 0x05: 0x21, 0x06: 0x22, // 1..5
	0x07: 0x23, 0x08: 0x24, 0x09: 0x25, 0x0A: 0x26, 0x0B: 0x27, // 6..0
	0x0C: 0x2D,                                                 // Minus
	0x0D: 0x2E,                                                 // Equal
	0x0E: 0x2A,                                                 // Backspace
	0x0F: 0x2B,                                                 // Tab
	0x10: 0x14, 0x11: 0x1A, 0x12: 0x08, 0x13: 0x15, 0x14: 0x17, // q w e r t
	0x15: 0x1C, 0x16: 0x18, 0x17: 0x0C, 0x18: 0x12, 0x19: 0x13, // y u i o p
	0x1A: 0x2F,                                                 // LeftBracket
	0x1B: 0x30,                                                 // RightBracket
	0x1C: 0x28,                                                 // Enter
	0x1D: 0xE0,                                                 // LeftCtrl
	0x1E: 0x04, 0x1F: 0x16, 0x20: 0x07, 0x21: 0x09, 0x22: 0x0A, // a s d f g
	0x23: 0x0B, 0x24: 0x0D, 0x25: 0x0E, 0x26: 0x0F, // h j k l
	0x27: 0x33,                                                 // Semicolon
	0x28: 0x34,                                                 // Quote
	0x29: 0x35,                                                 // Grave (key left of 1)
	0x2A: 0xE1,                                                 // LeftShift
	0x2B: 0x31,                                                 // Backslash (ISO: key left of Enter)
	0x2C: 0x1D, 0x2D: 0x1B, 0x2E: 0x06, 0x2F: 0x19, 0x30: 0x05, // z x c v b
	0x31: 0x11, 0x32: 0x10, // n m
	0x33: 0x36,                                                 // Comma
	0x34: 0x37,                                                 // Period
	0x35: 0x38,                                                 // Slash
	0x36: 0xE5,                                                 // RightShift
	0x37: 0x55,                                                 // KP *
	0x38: 0xE2,                                                 // LeftAlt
	0x39: 0x2C,                                                 // Space
	0x3A: 0x39,                                                 // CapsLock
	0x3B: 0x3A, 0x3C: 0x3B, 0x3D: 0x3C, 0x3E: 0x3D, 0x3F: 0x3E, // F1..F5
	0x40: 0x3F, 0x41: 0x40, 0x42: 0x41, 0x43: 0x42, 0x44: 0x43, // F6..F10
	0x45: HIDNumLock,
	0x46: 0x47,                         // ScrollLock
	0x47: 0x5F, 0x48: 0x60, 0x49: 0x61, // KP 7 8 9
	0x4A: 0x56,                         // KP -
	0x4B: 0x5C, 0x4C: 0x5D, 0x4D: 0x5E, // KP 4 5 6
	0x4E: 0x57,                         // KP +
	0x4F: 0x59, 0x50: 0x5A, 0x51: 0x5B, // KP 1 2 3
	0x52: 0x62,                                     // KP 0
	0x53: 0x63,                                     // KP .
	0x56: 0x64,                                     // NonUS backslash ("<>" on AZERTY)
	0x57: 0x44,                                     // F11
	0x58: 0x45,                                     // F12
	0x59: 0x67,                                     // KP =
	0x64: 0x68, 0x65: 0x69, 0x66: 0x6A, 0x67: 0x6B, // F13..F16
	0x68: 0x6C, 0x69: 0x6D, 0x6A: 0x6E, 0x6B: 0x6F, // F17..F20
}

var pcExtended = [0x80]uint8{
	0x1C: 0x58, // KP Enter
	0x1D: 0xE4, // RightCtrl
	0x20: 0x7F, // Mute
	0x2E: 0x81, // VolumeDown
	0x30: 0x80, // VolumeUp
	0x35: 0x54, // KP /
	0x36: 0xE5, // RightShift (some keyboards flag it extended)
	0x37: 0x46, // PrintScreen
	0x38: 0xE6, // RightAlt / AltGr
	0x45: HIDNumLock,
	0x47: 0x4A, // Home
	0x48: 0x52, // Up
	0x49: 0x4B, // PageUp
	0x4B: 0x50, // Left
	0x4D: 0x4F, // Right
	0x4F: 0x4D, // End
	0x50: 0x51, // Down
	0x51: 0x4E, // PageDown
	0x52: 0x49, // Insert
	0x53: 0x4C, // Delete
	0x5B: 0xE3, // LeftWin
	0x5C: 0xE7, // RightWin
	0x5D: 0x65, // Application (menu)
}
